// Bundle the existing, trusted SVG assets: no external CDN or extra HACS files required.
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
const icons = {};
for (const [style, directory] of [['style1','icons'],['style2','icons2']]) {
  icons[style] = {};
  for (const name of readdirSync(new URL(`../src/${directory}/`, import.meta.url)).filter(name => name.endsWith('.svg')).sort()) {
    icons[style][name.slice(0,-4)] = `data:image/svg+xml;base64,${Buffer.from(readFileSync(new URL(`../src/${directory}/${name}`, import.meta.url))).toString('base64')}`;
  }
}
writeFileSync(new URL('../src/bundled-weather-icons.js', import.meta.url), `// Generated by scripts/generate-weather-icons.mjs from src/icons and src/icons2.\nexport default ${JSON.stringify(icons, null, 2)};\n`);
