import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
const window = new Window();
for (const key of ['window','document','customElements','HTMLElement','Element','Document','ShadowRoot','CSSStyleSheet','ResizeObserver','Event']) globalThis[key] = key === 'window' ? window : window[key];
await import('../src/main.js');
const card = document.createElement('weather-chart-card');
card.setConfig({entity: 'weather.home', layout: 'modern', show_time: true, show_last_changed: true});
let callback;
let subscriptions = 0;
let unsubscribed = 0;
const weather = {state:'partlycloudy', last_updated:new Date().toISOString(), attributes:{temperature:19.7, humidity:83, pressure:1017, pressure_unit:'hPa', wind_speed:10,wind_speed_unit:'km/h',wind_bearing:90,supported_features:3}};
const hass = {language:'de', states:{'weather.home':weather},config:{unit_system:{temperature:'°C'}},connection:{subscribeMessage: async cb => {callback = cb; subscriptions++; return () => unsubscribed++;}}};
card.hass = hass;
document.body.append(card);
await card.updateComplete;
await new Promise(resolve => setTimeout(resolve, 30));
assert.equal(subscriptions,1);
assert.ok(card.shadowRoot.textContent.includes('Keine Vorhersagedaten'));
callback({forecast:Array.from({length:7}, (_,i) => ({datetime:new Date(Date.now()+i*86400000).toISOString(),temperature:i === 1 ? null : 22+i,templow:i === 2 ? undefined : 12+i, condition:'sunny',wind_speed:10}))});
await card.updateComplete;
assert.equal(card.shadowRoot.querySelectorAll('.days span').length,5);
assert.equal(card.shadowRoot.querySelector('#forecastChart'),null);
assert.ok(!card.shadowRoot.innerHTML.includes('NaN'));
assert.ok(card.clockInterval);
card.remove();
await Promise.resolve();
await Promise.resolve();
assert.equal(unsubscribed,1);
assert.equal(card.clockInterval,null);
document.body.append(card);
await card.updateComplete;
assert.equal(subscriptions,2);
card.setConfig({entity:'weather.home',layout:'modern',forecast:{type:'hourly',number_of_forecasts:3}});
await card.updateComplete;
await new Promise(resolve => setTimeout(resolve, 30));
assert.equal(subscriptions,3);
assert.equal(unsubscribed,2);
card.remove();
await window.happyDOM.abort();
console.log('Card rendering, missing sun, five-day default and subscription lifecycle tests passed');
